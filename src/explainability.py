import numpy as np
import pandas as pd
import streamlit as st
import plotly.express as px
from sklearn.ensemble import RandomForestClassifier
from sklearn.inspection import permutation_importance
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score

def render_cluster_explainability(result, matrix, feature_metadata):
    st.header("Section 10 — Cluster Explainability")
    st.write("Because clustering is unsupervised, there is no ground-truth target to explain. This section uses cluster membership as a temporary label to identify which input features help distinguish the fitted groups. These are descriptive diagnostics, not causal explanations.")

    clustered = result["clustered"]
    feature_names = None
    # The matrix columns align to transformed feature names if supported by the fitted preprocessor.
    # Prefer the feature names generated by the ColumnTransformer.
    st.subheader("Feature importance for distinguishing cluster assignments")
    try:
        names = list(result["preprocessor"].get_feature_names_out())
        if len(names) != matrix.shape[1]:
            names = [f"feature_{i}" for i in range(matrix.shape[1])]
    except Exception:
        names = [f"feature_{i}" for i in range(matrix.shape[1])]

    labels = np.asarray(result["labels"])
    if len(np.unique(labels)) < 2:
        st.info("At least two clusters are required to compute feature importance.")
        return

    max_rows = min(len(matrix), 8000)
    X = np.asarray(matrix[:max_rows])
    y = labels[:max_rows]
    if len(np.unique(y)) < 2:
        st.info("The selected sample contains fewer than two clusters.")
        return

    model = RandomForestClassifier(n_estimators=150, random_state=42, class_weight="balanced_subsample")
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=42, stratify=y
    )
    model.fit(X_train, y_train)
    predictions = model.predict(X_test)
    accuracy = accuracy_score(y_test, predictions)
    st.metric("Holdout cluster-label accuracy", f"{accuracy:.3f}")
    st.caption("High accuracy means the cluster assignments can be approximated from the features; it does not prove the clusters are correct.")

    importances = pd.DataFrame({
        "Feature": names,
        "Random forest importance": model.feature_importances_,
    }).sort_values("Random forest importance", ascending=False)
    top_n = st.slider("Number of features to display", min_value=5, max_value=min(30, len(importances)), value=min(15, len(importances)))
    top = importances.head(top_n).sort_values("Random forest importance")
    st.plotly_chart(px.bar(top, x="Random forest importance", y="Feature", orientation="h",
                           title="Features that distinguish the cluster labels"), use_container_width=True)
    st.dataframe(importances.head(top_n), use_container_width=True, hide_index=True)

    st.subheader("Permutation importance (optional)")
    if st.button("Calculate permutation importance"):
        perm = permutation_importance(model, X_test, y_test, n_repeats=5, random_state=42, n_jobs=-1)
        perm_df = pd.DataFrame({
            "Feature": names,
            "Mean accuracy decrease": perm.importances_mean,
            "Standard deviation": perm.importances_std,
        }).sort_values("Mean accuracy decrease", ascending=False)
        st.dataframe(perm_df.head(top_n), use_container_width=True, hide_index=True)
        st.download_button("Download feature importance CSV",
                           perm_df.to_csv(index=False).encode("utf-8"),
                           file_name="cluster_feature_importance.csv", mime="text/csv")

    st.warning("Feature importance depends on the fitted clustering, preprocessing, and the surrogate classifier. Correlated features can share or distort importance; do not interpret importance as causal impact.")
